import type { PlannerRound } from '@cbi/interview-engine';
import { compareAttempts } from '@cbi/scoring-core';
import {
  ReportContent,
  type CompetencyCategory,
  type ConfidenceLevel,
  type InterviewLanguagePreference,
  type InterviewMode,
  type ReadinessBand,
  type RecommendationsAi,
  type RoleAnalysis,
  type RoundType,
} from '@cbi/shared-types';
import type { CodingReportItem, IntegritySummary } from '@cbi/shared-types';
import type { OutputLanguage } from './language.js';
import { quoteFound } from './quotes.js';
import { fallbackMessages, fill } from './report-messages.js';

export const REPORT_DISCLAIMER =
  'This report was generated by AI from your practice interview answers. It is an estimate to help you prepare, not a hiring decision or a guarantee of any outcome. Scores are based only on what you said in this interview.';

/** Evidence items shown per dimension in the report. */
const EVIDENCE_PER_DIMENSION = 4;

export interface ReportDimensionInput {
  key: string;
  name: string;
  category: CompetencyCategory;
  weight: number;
  score: number | null;
  rationale: string | null;
  fallback: boolean;
}

export interface ReportEvidenceInput {
  id: string;
  questionId: string;
  competencyKey: string;
  claim: string;
  strength: number;
  quote: string | null;
}

export interface ReportTurnInput {
  seq: number;
  questionId: string;
  roundIdx: number;
  roundType: RoundType;
  question: string;
  answer: string | null;
}

export interface ReportInputs {
  header: {
    title: string;
    companyName: string | null;
    mode: InterviewMode;
    language: InterviewLanguagePreference;
    startedAt: Date | null;
    endedAt: Date | null;
    activeMs: number;
    endReason: string | null;
  };
  rounds: readonly PlannerRound[];
  turns: readonly ReportTurnInput[];
  dimensions: readonly ReportDimensionInput[];
  evidence: readonly ReportEvidenceInput[];
  overall: {
    score: number | null;
    band: ReadinessBand;
    confidence: {
      level: ConfidenceLevel;
      value: number;
      factors: {
        independentQuestions: number;
        practicalEvidence: number;
        consistency: number;
        completeness: number;
      };
    };
    assessedWeight: number;
  };
  recommendations: Pick<RecommendationsAi, 'summary' | 'strengths' | 'gaps' | 'plan'>;
  skills: RoleAnalysis['skills'];
  showTranscript: boolean;
  previous: {
    sessionId: string;
    overall: number | null;
    endedAt: Date | null;
    dimensions: readonly { key: string; name: string; score: number | null }[];
  } | null;
  /** Session observations (only when the interview tracked them). Never scored. */
  integrity?: IntegritySummary | null;
  /** Coding problems and their judged results. */
  coding?: CodingReportItem[];
}

const mentions = (haystack: string, needle: string) =>
  needle.trim().length > 1 && haystack.toLowerCase().includes(needle.trim().toLowerCase());

/**
 * A quote is shown as the candidate's words only if it is in their answer.
 * Extraction already removes unverifiable quotes; this also covers evidence
 * stored before that check. Questions answered with code (no text answer)
 * keep the extractor-verified quote.
 */
function shownQuote(quote: string | null, answer: string | null | undefined): string | null {
  if (!quote?.trim()) return null;
  if (!answer?.trim()) return quote;
  return quoteFound(quote, answer) ? quote : null;
}

/** Assembles the candidate-facing report. Pure: the same inputs give the same report. */
export function buildReportContent(input: ReportInputs): ReportContent {
  const questionText = new Map(input.turns.map((t) => [t.questionId, t.question]));
  const answerText = new Map(input.turns.map((t) => [t.questionId, t.answer]));
  const dimensionKeys = new Set(input.dimensions.map((d) => d.key));
  const keepKey = (key: string | null) => (key && dimensionKeys.has(key) ? key : null);

  const dimensions = input.dimensions.map((d) => ({
    key: d.key,
    name: d.name,
    category: d.category,
    weight: d.weight,
    score: d.score,
    rationale: d.rationale,
    fallback: d.fallback,
    evidence: input.evidence
      .filter((e) => e.competencyKey === d.key)
      .sort(
        (a, b) =>
          Math.abs(b.strength) - Math.abs(a.strength) ||
          b.strength - a.strength ||
          a.id.localeCompare(b.id),
      )
      .slice(0, EVIDENCE_PER_DIMENSION)
      .map((e) => ({
        id: e.id,
        claim: e.claim,
        strength: e.strength,
        quote: shownQuote(e.quote, answerText.get(e.questionId)),
        questionId: e.questionId,
        question: questionText.get(e.questionId) ?? '',
      })),
  }));

  const corpus = [
    ...input.dimensions.map((d) => d.name),
    ...input.evidence.map((e) => e.claim),
    ...input.turns.map((t) => t.question),
  ].join('\n');

  const deltas = input.previous
    ? compareAttempts([
        { dimensions: input.previous.dimensions },
        { dimensions: input.dimensions.map((d) => ({ key: d.key, name: d.name, score: d.score })) },
      ])
        .filter((d) => d.delta !== null)
        .map((d) => ({ key: d.key, name: d.name, delta: d.delta! }))
    : [];

  return ReportContent.parse({
    schemaVersion: 1,
    header: {
      title: input.header.title,
      companyName: input.header.companyName,
      mode: input.header.mode,
      language: input.header.language,
      startedAt: input.header.startedAt?.toISOString() ?? null,
      endedAt: input.header.endedAt?.toISOString() ?? null,
      durationSec: Math.round(input.header.activeMs / 1000),
      endReason: input.header.endReason,
    },
    overall: input.overall,
    summary: input.recommendations.summary,
    dimensions,
    strengths: input.recommendations.strengths.map((s) => ({
      text: s.text,
      dimensionKey: keepKey(s.dimensionKey),
    })),
    gaps: input.recommendations.gaps.map((g) => ({
      text: g.text,
      dimensionKey: keepKey(g.dimensionKey),
    })),
    rounds: input.rounds.map((r, idx) => {
      const turns = input.turns.filter((t) => t.roundIdx === idx);
      return {
        type: r.type,
        state: r.state,
        questions: turns.length,
        answered: turns.filter((t) => t.answer !== null && t.answer.trim() !== '').length,
        durationSec: Math.round(r.budgetMs / 1000),
      };
    }),
    coverage: input.skills.map((s) => ({
      skill: s.name,
      sources: s.sources,
      inResume: s.inResume,
      assessed: mentions(corpus, s.name),
    })),
    plan: input.recommendations.plan,
    previous: input.previous
      ? {
          sessionId: input.previous.sessionId,
          overall: input.previous.overall,
          endedAt: input.previous.endedAt?.toISOString() ?? null,
          deltas,
        }
      : null,
    transcript: input.showTranscript
      ? [...input.turns]
          .sort((a, b) => a.seq - b.seq)
          .map((t) => ({
            seq: t.seq,
            roundType: t.roundType,
            question: t.question,
            answer: t.answer,
          }))
      : null,
    integrity: input.integrity ?? null,
    ...(input.coding?.length ? { coding: input.coding } : {}),
    disclaimer: REPORT_DISCLAIMER,
  });
}

/**
 * Plain recommendations from the scores alone, used when the recommendations
 * model is unavailable so the report is never blocked. Written in the
 * candidate's output language (dimension names stay as the blueprint has them).
 */
export function fallbackRecommendations(
  dims: readonly Pick<ReportDimensionInput, 'key' | 'name' | 'score'>[],
  language: OutputLanguage = 'en',
): RecommendationsAi {
  const m = fallbackMessages(language);
  const named = (template: string, name: string) => fill(template, { name });
  const scored = dims
    .filter((d) => d.score !== null)
    .sort((a, b) => b.score! - a.score! || a.key.localeCompare(b.key));
  const strongest = scored.filter((d) => d.score! >= 65).slice(0, 3);
  const weakest = [...scored]
    .reverse()
    .filter((d) => d.score! < 65)
    .slice(0, 3);
  const focus = weakest.length ? weakest : scored.slice(-2).reverse();
  const unscored = dims.filter((d) => d.score === null).slice(0, 2);
  type PlanItem = RecommendationsAi['plan']['next24h'][number];
  const item = (d: { key: string; name: string }, action: string, why: string): PlanItem => ({
    action: named(action, d.name),
    why: named(why, d.name),
    dimensionKey: d.key,
  });
  const targets = [...focus, ...unscored];
  const first = targets[0] ?? scored[0] ?? dims[0];
  return {
    summary: scored.length ? m.summaryScored : m.summaryUnscored,
    strengths: strongest.map((d) => ({ text: named(m.strength, d.name), dimensionKey: d.key })),
    gaps: [
      ...weakest.map((d) => ({ text: named(m.gapLimited, d.name), dimensionKey: d.key })),
      ...unscored.map((d) => ({ text: named(m.gapUnassessed, d.name), dimensionKey: d.key })),
    ].slice(0, 5),
    plan: {
      next24h: first
        ? [item(first, m.examplesAction, m.examplesWhy)]
        : [{ action: m.genericExamplesAction, why: m.genericExamplesWhy, dimensionKey: null }],
      next3Days: (targets.length ? targets : scored)
        .slice(0, 3)
        .map((d) => item(d, m.starAction, m.starWhy))
        .concat(
          targets.length || scored.length
            ? []
            : [{ action: m.rehearseAction, why: m.rehearseWhy, dimensionKey: null }],
        ),
      next7Days: [{ action: m.retakeAction, why: m.retakeWhy, dimensionKey: null }],
    },
  };
}
